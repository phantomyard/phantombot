/**
 * Codegen: embed the OpenCode provider package into a TypeScript constants
 * module so the compiled single-ELF binary can stamp it onto disk at install
 * time (see src/connectors/acp/installOpencode.ts).
 *
 * Same reasoning as scripts/genVscodeVsix.ts and scripts/genPiExtensionAssets.ts:
 * `bun build --compile` produces ONE file with no repo alongside it, and
 * `import ... with { type: "..." }` is not tsc-safe in this toolchain. A plain
 * generated `.ts` with the bytes as a base64 string literal keeps the binary
 * self-contained.
 *
 * Unlike the .vsix (whose zip bytes are not reproducible and whose source may
 * legitimately drift), this asset is a TEXT file that ships in the repo, so the
 * generated module also records its sha256 and
 * tests/lib-opencodeProviderAsset.test.ts fails when the two disagree. That
 * closes the "edited the source, forgot to regenerate" hole the .vsix shipped
 * a stale release through — the CI check is byte-exact.
 *
 * Run: bun run gen:opencode-provider
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sourcePath = join(root, "src/connectors/acp/opencode/provider/index.mjs");
const outPath = join(root, "src/lib/opencodeProviderAsset.generated.ts");

const bytes = readFileSync(sourcePath);
const sha256 = createHash("sha256").update(bytes).digest("hex");
const base64 = bytes.toString("base64");

const contents = `// GENERATED by scripts/genOpencodeProviderAsset.ts — DO NOT EDIT.
// Run: bun run gen:opencode-provider
//
// The OpenCode provider package (src/connectors/acp/opencode/provider/index.mjs)
// embedded as base64 so a compiled phantombot binary can write it to disk when
// it registers itself with OpenCode. The sha256 pins the exact source; the test
// in tests/lib-opencodeProviderAsset.test.ts re-derives it from the file on
// disk, so a stale asset fails CI instead of shipping.

/** Filename the asset is written as on disk (OpenCode imports it by path). */
export const OPENCODE_PROVIDER_FILENAME = "index.mjs";

/** sha256 of the provider source, hex. */
export const OPENCODE_PROVIDER_SHA256 = "${sha256}";

/** base64 of the provider source. */
export const OPENCODE_PROVIDER_SOURCE_BASE64 =
  "${base64}";
`;

writeFileSync(outPath, contents, "utf8");
process.stdout.write(
  `wrote ${outPath}\n  source: ${sourcePath}\n  bytes:  ${bytes.length}\n  sha256: ${sha256}\n`,
);
